"""Model stand-ins for human review steps (docs/PAPER_TODO.md, scorecard S8 and S11).  Each call is one request at temperature 0.

python tools/llm_review.py proofs OUT_DIR MODELS.json [MODEL=vertex-gemini-argon] [CAP_USD=2]
    every lemma, theorem, proposition and corollary of the Theory section checked by the model; JSON list of issues.
python tools/llm_review.py mock OUT_DIR MODELS.json [MODEL=vertex-gemini-argon] [CAP_USD=3]
    three independent ISSTA-style reviews of the whole paper (theory, empirical, practice), each with scores and weaknesses.

These do NOT replace a human reader or the advisor; they are labelled as model reviews wherever they are used.
"""
import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools"))
from gatekeeper_lite import b9  # noqa: E402

LATEX = ROOT / "docs/paper/latex"
ORDER = ["intro", "motivation", "problem", "approach", "theory", "implementation", "evaluation", "threats", "related", "conclusion"]

PROOF_SYSTEM = """You are a careful mathematical referee for a software-engineering venue. You receive the problem formulation and the
theory section of a paper (LaTeX). Check EVERY lemma, theorem, proposition, corollary and remark with a proof: is the statement
precise, are all assumptions stated, does the proof prove exactly the statement, are constants and inequalities right, and are
there counterexamples? Do not comment on style. Reply with JSON only:
{"items": [{"label": "<e.g. Lemma 1>", "verdict": "correct" | "minor_issue" | "major_issue" | "wrong",
            "issue": "<precise description, empty if correct>", "fix": "<concrete fix, empty if correct>"}],
 "overall": "<two sentences>"}"""

PERSONAS = {
    "theory": "an expert in sequential testing, e-values and anytime-valid inference",
    "empirical": "an expert in empirical software engineering, pre-registration and threats to validity",
    "practice": "an expert in automated program repair, coding agents and code reuse in industry",
}
MOCK_SYSTEM = """You are %s, reviewing a full research paper submitted to ISSTA (ACM International Symposium on Software Testing
and Analysis, double-anonymous). Review it as a strict but fair program-committee member. Reply with JSON only:
{"summary": "<3 sentences>", "novelty": 1-5, "soundness": 1-5, "evidence": 1-5, "clarity": 1-5,
 "overall": "strong reject" | "reject" | "weak reject" | "weak accept" | "accept" | "strong accept",
 "strengths": ["..."], "weaknesses": [{"id": "W1", "severity": "major" | "minor", "text": "...", "what_would_fix_it": "..."}],
 "questions_to_authors": ["..."]}"""


def paper_text(sections=None):
    parts = []
    main = (LATEX / "main.tex").read_text()
    m = re.search(r"\\begin\{abstract\}(.*?)\\end\{abstract\}", main, re.S)
    if m and sections is None:
        parts.append("ABSTRACT\n" + m.group(1))
    for name in (sections or ORDER):
        p = LATEX / "sections" / (name + ".tex")
        if p.is_file():
            parts.append(inline_inputs(p.read_text()))
    if sections is None:
        dm = re.search(r"\\section\*\{Data Availability\}.*?(?=\\bibliography|\\end\{document\})", main, re.S)
        if dm:
            parts.append(dm.group(0))
    return "\n\n".join(parts)


def inline_inputs(text):
    """Replace \\input{sections/x} by the file's content, in place (the first review run appended it at the end instead)."""
    def rep(m):
        p = LATEX / (m.group(1) if m.group(1).endswith(".tex") else m.group(1) + ".tex")
        return p.read_text() if p.is_file() else m.group(0)
    return re.sub(r"\\input\{([^}]+)\}", rep, text)


def parse_json(text):
    m = re.search(r"\{.*\}", text or "", re.S)
    try:
        return json.loads(m.group(0)) if m else {"parse_error": (text or "")[:500]}
    except ValueError:
        return {"parse_error": (text or "")[:500]}


def call(client, cfg, guard, system, user, max_out=8000):
    msgs = [{"role": "system", "content": system}, {"role": "user", "content": user}]
    guard.check(msgs, max_out, cfg["prices_usd_per_mtok"])
    r = client.complete(cfg["model_id"], msgs, max_out, 0.0, 1)
    guard.add(r["usage"], cfg["prices_usd_per_mtok"])
    return parse_json(r["text"])


def run(mode, client, cfg, cap):
    guard = b9.SpendGuard(cap)
    if mode == "proofs":
        out = {"mode": mode, "model": cfg["model_id"],
               "review": call(client, cfg, guard, PROOF_SYSTEM, paper_text(["problem", "theory"]), 12000)}
    else:
        text = paper_text()
        out = {"mode": mode, "model": cfg["model_id"],
               "reviews": {k: call(client, cfg, guard, MOCK_SYSTEM % v, text, 8000) for k, v in PERSONAS.items()}}
    out["spent_usd"] = guard.spent_usd
    return out


def to_markdown(res):
    lines = ["# Model review (%s, %s)" % (res["mode"], res["model"]), "",
             "*Generated by a model as a stand-in for a human step; not a human review. Cost: %.4f USD.*" % res["spent_usd"], ""]
    if res["mode"] == "proofs":
        rv = res["review"]
        lines += ["| Item | Verdict | Issue | Fix |", "|---|---|---|---|"]
        for it in rv.get("items", []):
            lines.append("| %s | %s | %s | %s |" % (it.get("label"), it.get("verdict"), str(it.get("issue", "")).replace("|", "/"),
                                                  str(it.get("fix", "")).replace("|", "/")))
        lines += ["", "**Overall:** " + str(rv.get("overall", rv.get("parse_error", "")))]
    else:
        for k, rv in res["reviews"].items():
            lines += ["## Reviewer: %s" % k, "", "Overall: **%s**; novelty %s, soundness %s, evidence %s, clarity %s" % (
                rv.get("overall"), rv.get("novelty"), rv.get("soundness"), rv.get("evidence"), rv.get("clarity")), "",
                str(rv.get("summary", rv.get("parse_error", ""))), "", "Weaknesses:"]
            for w in rv.get("weaknesses", []):
                lines.append("- **%s (%s):** %s *Fix:* %s" % (w.get("id"), w.get("severity"), w.get("text"), w.get("what_would_fix_it")))
            lines += ["", "Questions: " + "; ".join(rv.get("questions_to_authors", [])), ""]
    return "\n".join(lines) + "\n"


def main(argv):
    mode, out_dir, models_path = argv[:3]
    name = argv[3] if len(argv) > 3 else "vertex-gemini-argon"
    cap = float(argv[4]) if len(argv) > 4 else 3.0
    from cohort_inner import RefreshingClient
    cfg = next(m for m in json.loads(Path(models_path).read_text())["models"] if m["name"] == name)
    client = RefreshingClient(cfg["base_url"].replace("{GCP_PROJECT}", os.environ.get("GCP_PROJECT", "")), cfg["key_env"], cfg.get("extra", {}))
    res = run(mode, client, cfg, cap)
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    stem = "PROOF_REVIEW" if mode == "proofs" else "MOCK_REVIEWS"
    (out / (stem + ".json")).write_text(json.dumps(res, indent=1))
    (out / (stem + ".md")).write_text(to_markdown(res))
    print(json.dumps({"mode": mode, "spent_usd": round(res["spent_usd"], 4)}))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
